// Conversation-surface strings, localized per half (audit C3).
//
// The product premise is two people at a table who do NOT share a language —
// so each half of the screen renders its chrome (stage microcopy, notices,
// welcome copy, the network pill) in that half's reader's language, keyed by
// their `speakerLanguage`. Settings and onboarding remain English: those
// surfaces are owner-mediated and single-reader.
//
// Scope discipline: only what a reader must glance at mid-conversation lives
// here. Notice sentences are keyed by `NoticeKey` (store) so services never
// carry display text — they log the raw error and store the key.

import type { NoticeKey, SpeakerNotice } from '../store/conversationStore';
import { getLanguage } from '../app/languages';

export interface SurfaceStrings {
  // Stage microcopy (single glanceable words).
  readonly listening: string;
  readonly thinking: string;
  readonly speaking: string;
  readonly error: string;
  // Network pill.
  readonly online: string;
  readonly offline: string;
  readonly connecting: string;
  // Welcome copy.
  readonly holdToSpeak: string;
  readonly justSpeak: string;
  readonly tapToExit: string;
  // Hands-free unrouted blink (one word).
  readonly unrouted: string;
  // Seam-control hint label, shown until the reader first uses hands-free.
  readonly handsFree: string;
  // Notice sentences. `noVoice` contains a {lang} placeholder.
  readonly notices: Readonly<Record<NoticeKey, string>>;
}

