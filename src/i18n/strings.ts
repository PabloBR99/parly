/** Strings for a half whose reader speaks `langCode`. Falls back to English
 *  for languages outside the picker set ('' during first-run included). */
export function stringsFor(langCode: string): SurfaceStrings {
  if (!langCode) return en;
  const primary = langCode.split(/[-_]/)[0].toLowerCase();
  return TABLE[primary] ?? en;
}

/** Resolve a store notice into display text in the reader's language.
 *  The {lang} placeholder renders as the endonym — the one name for a
 *  language its own speaker always recognizes. */
export function noticeText(readerLang: string, notice: SpeakerNotice): string {
  const template = stringsFor(readerLang).notices[notice.key];
  if (notice.lang) {
    return template.replace('{lang}', getLanguage(notice.lang.split(/[-_]/)[0].toLowerCase()).endonym);
  }
  return template;
}
